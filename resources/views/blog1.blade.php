<div class="content">
  <p class="pembuka">Setiap warga memiliki hak untuk menyampaikan keluhan, saran, maupun aspirasi terhadap layanan publik. Namun, agar laporan benar-benar ditindaklanjuti dengan cepat dan tepat, cara penyampaiannya juga harus efektif. Berikut beberapa tips agar pengaduan Anda lebih mudah diproses oleh pihak berwenang:</p>
  
  <h2>✅ 1. Jelaskan Masalah dengan Jelas dan Spesifik</h2>
  <p class="isi-poin">Tulis pengaduan dengan bahasa yang mudah dipahami. Hindari kalimat bertele-tele. Sebutkan apa masalahnya, kapan terjadi, dan di mana lokasinya.</p>

  <h2>✅ 2. Pilih Kategori Pengaduan yang Tepat</h2>
  <p class="isi-poin">Setiap platform biasanya menyediakan kategori seperti keamanan, lingkungan, infrastruktur, dll. Pilih kategori yang sesuai agar pengaduan langsung diteruskan ke instansi yang berwenang.</p>

  <h2>✅ 3. Sertakan Bukti Pendukung</h2>
  <p class="isi-poin">Unggah foto, video, atau dokumen yang mendukung laporanmu. Bukti visual membuat pengaduan lebih dipercaya dan lebih mudah diverifikasi.</p>

  <h2>✅ 4. Gunakan Bahasa yang Sopan dan Objektif</h2>
  <p class="isi-poin">Jangan menggunakan kata-kata kasar atau menyudutkan pihak tertentu. Fokus pada masalah, bukan menyerang orang. Sopan santun meningkatkan peluang pengaduan diproses cepat.</p>
  
  <h2>✅ 5. Lengkapi Data Diri Secara Jelas</h2>
  <p class="isi-poin">Pastikan kamu mengisi data diri secara lengkap dan benar, seperti nama, alamat, dan kontak yang bisa dihubungi. Identitas ini penting agar petugas bisa menindaklanjuti laporan dengan tepat, serta menghubungi kamu jika diperlukan klarifikasi lebih lanjut.</p>

  <h2>✅ 6. Gunakan Platform Resmi</h2>
  <p class="isi-poin">Pastikan kamu menyampaikan pengaduan lewat kanal resmi seperti website pengaduan, aplikasi pemerintah, atau hotline pengaduan masyarakat. Ini menjamin laporanmu tercatat secara formal.</p>

  <p class="penutup">Dengan menyampaikan pengaduan secara jelas, sopan, dan lengkap, Anda turut berperan aktif dalam menciptakan pelayanan publik yang lebih baik dan lingkungan yang lebih tertib. Suara Anda sangat berarti — mari gunakan dengan bijak untuk perubahan yang positif.</p>
